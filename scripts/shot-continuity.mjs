import { chromium } from "playwright";
import { resolve } from "node:path";
const OUT = resolve(import.meta.dirname, "..", "shots");
const addDays = (iso, n) => { const d = new Date(iso + "T12:00:00"); d.setDate(d.getDate() + n); const p = (x) => String(x).padStart(2, "0"); return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`; };
const now = new Date();
const today = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}-${String(now.getDate()).padStart(2, "0")}`;
const browser = await chromium.launch({ channel: "chrome" });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await page.goto("http://localhost:5188/");
const n = await page.getByRole("button", { name: /^完成任务：/ }).count();
for (let i = 0; i < n; i++) await page.getByRole("button", { name: /^完成任务：/ }).first().click();
await page.getByRole("button", { name: "结束今天的学习" }).first().click();
await page.getByRole("button", { name: /完全掌握/ }).click();
await page.getByRole("button", { name: "完成并领取成长" }).click();
await page.getByRole("button", { name: "收下，明天继续" }).click();
await page.screenshot({ path: resolve(OUT, "15-hero-points.png") });
await page.getByRole("button", { name: "学习计划", exact: true }).first().click();
await page.getByRole("button", { name: `选择日期 ${addDays(today, 1)}` }).click();
await page.waitForTimeout(400);
await page.screenshot({ path: resolve(OUT, "16-plan-continuity.png") });
await browser.close();
console.log("continuity shots saved");
