import { chromium } from "playwright";
import { resolve } from "node:path";
const OUT = resolve(import.meta.dirname, "..", "shots");
const browser = await chromium.launch({ channel: "chrome" });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
await page.goto("http://localhost:5188/");
await page.getByLabel(/今日重点/).count();
await page.locator("nav.fixed button", { hasText: "笔记" }).first().click();
await page.waitForTimeout(400);
await page.getByLabel(/今日重点/).fill("移动端笔记：self 指向实例");
await page.waitForTimeout(900);
await page.screenshot({ path: resolve(OUT, "13-mobile-notes.png"), fullPage: true });
await page.locator("nav.fixed button", { hasText: "错题" }).first().click();
await page.waitForTimeout(300);
await page.getByRole("button", { name: /新增错题/ }).first().click();
await page.getByLabel("题目名称").fill("with 与 open 的区别");
await page.getByLabel(/错误原因/).fill("忘了 with 会自动关闭文件");
await page.getByRole("button", { name: "加入错题本", exact: true }).last().click();
await page.waitForTimeout(300);
await page.screenshot({ path: resolve(OUT, "14-mobile-mistakes.png"), fullPage: true });
await browser.close();
console.log("mobile shots saved");
